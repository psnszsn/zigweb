const std = @import("std");
const superhtml = @import("superhtml_attrs");
const Ast = superhtml.Ast;
const Attribute = superhtml.Attribute;

const htmx_fields: []const []const u8 = &.{
    "get",     "post",    "put",      "delete",      "patch",
    "trigger", "target",  "swap",     "swap_oob",    "include",
    "select",  "confirm", "push_url", "replace_url", "vals",
    "sync",    "boost",   "disable",  "preserve",    "encoding",
    "indicator",
};

// Attributes whose inheritance is opt-in via the `:inherited` postfix (htmx 4).
// A bool field per name lives in the generated `Inherited` struct.
const inheritable_fields: []const []const u8 = &.{
    "target",   "swap",        "include", "select", "confirm",
    "push_url", "replace_url", "vals",    "sync",   "boost",
};

const aria_prefix = "aria-";
const on_prefix = "on";

const tags: []const []const u8 = &.{
    "html",    "head",   "title",   "meta",    "link",   "body",
    "div",     "span",   "p",       "a",       "button", "input",
    "br",      "hr",     "ul",      "ol",      "li",     "h1",
    "h2",      "h3",     "section", "nav",     "header", "footer",
    "main",    "form",   "label",   "table",   "tr",     "td",
    "th",      "thead",  "tbody",   "script",  "img",    "textarea",
    "select",  "option", "time",    "article", "small",  "details",
    "summary",
};

pub fn main(init: std.process.Init) void {
    var buf: [8192]u8 = undefined;
    var w = std.Io.File.Writer.init(
        .{ .handle = std.posix.STDOUT_FILENO, .flags = .{ .nonblocking = false } },
        init.io,
        &buf,
    );
    const stdout = &w.interface;

    stdout.writeAll("// Generated by gen_attrs.zig — do not edit\n\n") catch return;

    stdout.writeAll(
        \\/// One `hx-status:<code>="<value>"` rule: `.{ code-pattern, value }`.
        \\/// The code is a string so wildcards work: "422", "4xx", "5xx", "50x".
        \\pub const StatusRule = struct { []const u8, []const u8 };
        \\
        \\
    ) catch return;

    stdout.writeAll(
        \\/// Opt-in inheritance (htmx 4 made inheritance explicit). A true field flips
        \\/// the matching `Hx` attribute's serialization from `hx-x` to `hx-x:inherited`.
        \\
    ) catch return;
    stdout.writeAll("pub const Inherited = struct {\n") catch return;
    for (inheritable_fields) |name| {
        stdout.print("    {s}: bool = false,\n", .{name}) catch return;
    }
    stdout.writeAll("};\n\n") catch return;

    stdout.writeAll("pub const Hx = struct {\n") catch return;
    for (htmx_fields) |hx_name| {
        stdout.print("    {s}: ?[]const u8 = null,\n", .{hx_name}) catch return;
    }
    stdout.writeAll("    inherited: Inherited = .{},\n") catch return;
    stdout.writeAll("    status: []const StatusRule = &.{},\n") catch return;
    stdout.writeAll("};\n\n") catch return;

    stdout.writeAll("pub const Aria = struct {\n") catch return;
    for (Attribute.global.list) |named| {
        if (!std.mem.startsWith(u8, named.name, aria_prefix)) continue;
        stdout.print("    {s}: ?[]const u8 = null,\n", .{named.name[aria_prefix.len..]}) catch return;
    }
    stdout.writeAll("};\n\n") catch return;

    stdout.writeAll("pub const On = struct {\n") catch return;
    for (Attribute.global.list) |named| {
        if (!std.mem.startsWith(u8, named.name, on_prefix)) continue;
        stdout.print("    @\"{s}\": ?[]const u8 = null,\n", .{named.name[on_prefix.len..]}) catch return;
    }
    stdout.writeAll("};\n\n") catch return;

    for (tags) |tag| {
        const kind = std.meta.stringToEnum(Ast.Kind, tag) orelse {
            stdout.print("pub const {s} = struct {{}};\n\n", .{tag}) catch return;
            continue;
        };

        const elem_set = Attribute.element_attrs.get(kind);
        const global_set = &Attribute.global;

        stdout.print("pub const {s} = struct {{\n", .{tag}) catch return;

        for ([_][]const Attribute.Named{ elem_set.list, global_set.list }) |list| {
            for (list) |named| {
                if (std.mem.startsWith(u8, named.name, aria_prefix)) continue;
                if (std.mem.startsWith(u8, named.name, on_prefix)) continue;
                const is_bool = named.model.rule == .bool;
                const type_name: []const u8 = if (is_bool) "?bool" else "?[]const u8";
                stdout.print("    @\"{s}\": {s} = null,\n", .{ named.name, type_name }) catch return;
            }
        }

        stdout.writeAll("    aria: Aria = .{},\n") catch return;
        stdout.writeAll("    hx: Hx = .{},\n") catch return;
        stdout.writeAll("    on: On = .{},\n") catch return;

        stdout.writeAll("};\n\n") catch return;
    }
    w.flush() catch return;
}
